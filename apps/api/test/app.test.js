// Mode développement (FAKE_DB=1) : site, CRM historique, routes /__dev/*, IA et WhatsApp simulés.
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createApp, ROOT } from '../src/app.js';

let api; let base;
before(async () => {
  for (const k of ['WHATSAPP_TOKEN', 'ANTHROPIC_API_KEY', 'WHISPER_API_KEY', 'TEAM_ALERT_NUMBERS', 'MONGODB_URI', 'AUTH_SECRET', 'AMANE_SETUP_CODE']) delete process.env[k];
  process.env.FAKE_AI = '1';
  api = await createApp({ fake: true, devPins: 'amel:1234' });
  const port = await api.listen(0, '127.0.0.1');
  base = `http://127.0.0.1:${port}`;
});
after(() => api.close());

test('site statique, CRM historique, 404 propres', async () => {
  const home = await fetch(base + '/');
  assert.equal(home.status, 200);
  assert.equal(await home.text(), fs.readFileSync(path.join(ROOT, 'site/vercel.html'), 'utf8'));
  const crm = await fetch(base + '/crm');
  assert.equal(crm.status, 200);
  assert.equal(crm.headers.get('x-robots-tag'), 'noindex, nofollow');
  const crmHtml = await crm.text();
  assert.ok(crmHtml.startsWith('<!doctype html>') && crmHtml.includes('/api/auth/me'), 'CRM source (mode serveur) enveloppé en document complet');
  assert.ok(crmHtml.includes(fs.readFileSync(path.join(ROOT, 'crm/index.html'), 'utf8').slice(0, 2000)));
  assert.equal((await fetch(base + '/favicon.svg')).headers.get('content-type'), 'image/svg+xml');
  const trav = await fetch(base + '/%2e%2e/package.json');
  assert.ok([403, 404].includes(trav.status));
  assert.ok(!(await trav.text()).includes('"mongodb"'));
  assert.equal((await fetch(base + '/nexiste-pas.html')).status, 404);
  const api404 = await fetch(base + '/api/nexiste-pas');
  assert.equal(api404.status, 404);
  assert.equal((await api404.json()).error, 'introuvable');
  const app = await fetch(base + '/app');
  assert.ok([200, 404].includes(app.status), 'le back-office est servi quand apps/web/dist existe');
});

test('API par HTTP : santé, connexion, fiches, compteur, synchro, WhatsApp simulé, IA simulée', async () => {
  const h = await (await fetch(base + '/api/health?detail=1')).json();
  assert.equal(h.ok, true);
  assert.equal(h.whatsapp, true);
  assert.equal(h.ia, true);
  assert.equal(h.fake, true);
  const login = await fetch(base + '/api/auth/login', { method: 'POST', headers: { 'content-type': 'application/json', origin: base }, body: JSON.stringify({ userId: 'amel', pin: '1234' }) });
  assert.equal(login.status, 200);
  const sc = login.headers.get('set-cookie');
  assert.ok(sc.includes('HttpOnly') && !sc.includes('Secure'), 'cookie non Secure en http local seulement');
  const cookie = sc.split(';')[0];
  const H = { cookie, 'content-type': 'application/json', origin: base };
  assert.equal((await fetch(base + '/api/auth/me', { headers: H })).status, 200);
  const put = await fetch(base + '/api/doc/clients/c1', { method: 'PUT', headers: H, body: JSON.stringify({ nom: 'Test', tel: '06 12 34 56 78' }) });
  assert.equal(put.status, 200);
  const n = await (await fetch(base + '/api/counter', { method: 'POST', headers: H, body: JSON.stringify({ key: 'devis-2026' }) })).json();
  assert.deepEqual(n, { n: 1 });
  const act = await (await fetch(base + '/api/activity?docId=c1', { headers: H })).json();
  assert.equal(act.items[0].resume, 'Création : Test');
  const inbound = await fetch(base + '/__dev/inbound', { method: 'POST', headers: H, body: JSON.stringify({ from: '33612345678', name: 'Jean', text: 'Hello, an Urus please' }) });
  assert.equal(inbound.status, 200);
  const out = await (await fetch(base + '/__dev/outbox')).json();
  const sent = out.items.filter((i) => i.kind === 'message');
  assert.equal(sent.length, 1);
  assert.equal(sent[0].body.to, '33612345678');
  assert.ok(out.items.some((i) => i.kind === 'ia'), 'IA simulée appelée');
  const s = await (await fetch(base + '/api/sync', { headers: H })).json();
  assert.equal(s.changes.clients.length, 1, 'client retrouvé par téléphone');
  assert.equal(s.changes.conversations[0].clientId, 'c1');
  assert.equal(s.changes.conversations[0].aiSummary, 'Demande de location simulée (IA de démonstration).');
  const inMsg = s.changes.messages.find((m) => m.dir === 'in');
  assert.equal(inMsg.translation, '[FR] Hello, an Urus please', 'traduction simulée');
  assert.equal(s.compteurs['devis-2026'], 1);
  const send = await fetch(base + '/api/whatsapp/send', { method: 'POST', headers: H, body: JSON.stringify({ convId: '33612345678', text: 'Avec plaisir.' }) });
  assert.equal(send.status, 200);
  const ai = await fetch(base + '/api/ai', { method: 'POST', headers: H, body: JSON.stringify({ messages: [{ role: 'user', content: 'x' }] }) });
  assert.equal(ai.status, 200);
  assert.match((await ai.json()).text, /démonstration/);
  const tr = await fetch(base + '/api/translate', { method: 'POST', headers: H, body: JSON.stringify({ text: 'Bonjour', to: 'EN' }) });
  assert.equal(tr.status, 200);
  assert.equal((await tr.json()).text, '[EN] Bonjour');
  assert.equal((await fetch(base + '/api/auth/logout', { method: 'POST', headers: H })).status, 200);
});

test('/__dev : vocal, image, position, contact, réaction, statut, horloge, tâches', async () => {
  const login = await fetch(base + '/api/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ userId: 'amel', pin: '1234' }) });
  const cookie = login.headers.get('set-cookie').split(';')[0];
  const H = { cookie, 'content-type': 'application/json' };
  const dev = (p, b) => fetch(base + p, { method: 'POST', headers: H, body: JSON.stringify(b) });
  await (await dev('/__dev/clock', { now: '2026-11-03T10:00:00Z' })).json();
  assert.equal((await (await fetch(base + '/__dev/state')).json()).now, '2026-11-03T10:00:00.000Z');
  const from = '971501234567';
  await dev('/__dev/inbound', { from, name: 'Khalid', type: 'audio', id: 'wamid.voc1' });
  await dev('/__dev/inbound', { from, type: 'image', caption: 'Mon passeport', id: 'wamid.img1' });
  await dev('/__dev/inbound', { from, type: 'location', lat: 48.87, lng: 2.3, locName: 'George V', id: 'wamid.loc1' });
  await dev('/__dev/inbound', { from, type: 'contacts', contact: { nom: 'Ali Ben', tel: '+971500000001' }, id: 'wamid.ct1' });
  await dev('/__dev/inbound', { from, type: 'reaction', reactionTo: 'wamid.img1', emoji: '👍', id: 'wamid.re1' });
  const s = await (await fetch(base + '/api/sync', { headers: H })).json();
  const ms = s.changes.messages.filter((m) => m.convId === from && m.dir === 'in');
  const voc = ms.find((m) => m.id === 'wamid.voc1');
  assert.equal(voc.type, 'audio');
  assert.ok(voc.media.photoId, 'vocal téléchargé');
  assert.match(voc.transcript, /voiture pour samedi/);
  assert.ok(ms.find((m) => m.id === 'wamid.img1').media.photoId);
  const media = await fetch(base + `/api/media/${voc.media.photoId}`, { headers: H });
  assert.equal(media.status, 200);
  assert.equal(media.headers.get('content-type'), 'audio/ogg');
  assert.equal((await fetch(base + `/api/media/${voc.media.photoId}`)).status, 401);
  assert.deepEqual(ms.find((m) => m.id === 'wamid.loc1').location, { lat: 48.87, lng: 2.3, name: 'George V' });
  assert.equal(ms.find((m) => m.id === 'wamid.ct1').contacts[0].nom, 'Ali Ben');
  assert.equal(ms.find((m) => m.id === 'wamid.re1').reactionTo, 'wamid.img1');
  const conv = s.changes.conversations.find((c) => c.id === from);
  assert.equal(conv.unread, 4, 'la réaction ne compte pas comme non lu');
  const outbox = (await (await fetch(base + '/__dev/outbox')).json()).items;
  const outMsg = outbox.filter((i) => i.kind === 'message' && i.body.to === from);
  assert.equal(outMsg.length, 1, 'une seule réponse automatique');
  await dev('/__dev/status', { id: outMsg[0].id, status: 'read' });
  const s2 = await (await fetch(base + '/api/sync', { headers: H })).json();
  assert.equal(s2.changes.messages.find((m) => m.id === outMsg[0].id).status, 'lu');
  await dev('/__dev/status', { id: outMsg[0].id, status: 'failed', code: 131026 });
  const run = await (await dev('/__dev/run', { job: 'alertes' })).json();
  assert.deepEqual(run, { sansReponse: 0, revisions: 0 });
  await dev('/__dev/clock', { now: null });
});
