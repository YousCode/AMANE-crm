  assert.equal(bad.status, 400);
  const ok = await call(H.doc, { method: 'POST', url: '/api/push/register', body: { token: 'ExponentPushToken[abcdefgh1234]', platform: 'ios' }, cookie });
  assert.deepEqual(ok.json, { ok: true });
