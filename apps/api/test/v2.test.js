  await call(H.doc, { method: 'POST', url: '/api/push/register', body: { token: 'ExponentPushToken[youssouf12345]', platform: 'android' }, cookie: cookieY });
  await postWebhook(inboundPayload({ name: 'Jean', text: 'Bonjour, une Urus svp' }));
  assert.equal(net.expoCalls.length, 1);
  const batch = net.expoCalls[0].body;
  assert.equal(batch.length, 1, 'seul le responsable (Amel) est notifié');
  assert.equal(batch[0].to, 'ExponentPushToken[abcdefgh1234]');
  assert.equal(batch[0].title, 'Nouvelle demande WhatsApp');
  assert.match(batch[0].body, /^Jean : Bonjour, une Urus svp/);
  assert.equal(batch[0].data.type, 'demande');
  net.expo((c) => ({ status: 200, json: { data: c.body.map(() => ({ status: 'error', details: { error: 'DeviceNotRegistered' } })) } }));
  await postWebhook(inboundPayload({ id: 'w2', text: 'Encore' }));
